#define FONT_W 8
#define FONT_H 8
#define FG 0x00FFFFFFu /* white text (B8G8R8X8: 0x00RRGGBB) */
#define BG 0x00000000u /* black background */

static u_int32_t g_cols, g_rows; /* console size in glyphs */
static u_int32_t g_cx, g_cy;     /* cursor column / row */
static int g_ready;

/**
 * Present the backing framebuffer to the host scanout.  virtio-gpu needs an
 * explicit transfer+flush; on the boot thread this is the only writer (views has
 * not claimed the screen yet — once it does, this sink is suspended).
 */
static void fbcon_present(void)
{
	aarch64_fb_present();
}

/**
 * Fill the whole framebuffer with @argb.
 */
static void fbcon_fill(u_int32_t argb)
{
	u_int32_t x, y;

	for (y = 0; y < virtio_gpu_height; y++)
	{
		u_int32_t *row = (u_int32_t *)(virtio_gpu_fb + (u_int64_t)y * virtio_gpu_pitch);
		for (x = 0; x < virtio_gpu_width; x++)
			row[x] = argb;
	}
}

/**
 * Draw one glyph cell (column @cx, row @cy) for character @c.
 */
static void fbcon_draw_glyph(u_int32_t cx, u_int32_t cy, unsigned char c)
{
	const u_int8_t *glyph;
	u_int32_t gx, gy, px0 = cx * FONT_W, py0 = cy * FONT_H;

	if (c < 0x20 || c > 0x7F)
		c = '?';
	glyph = g_font8x8[c - 0x20];

	for (gy = 0; gy < FONT_H; gy++)
	{
		u_int32_t *row = (u_int32_t *)(virtio_gpu_fb + (u_int64_t)(py0 + gy) * virtio_gpu_pitch);
		u_int8_t bits = glyph[gy];
		for (gx = 0; gx < FONT_W; gx++)
			row[px0 + gx] = (bits & (0x80u >> gx)) ? FG : BG;
	}
}

/**
 * Scroll the framebuffer up one text row (move rows 1.. up, clear the last).
 */
static void fbcon_scroll(void)
{
	u_int32_t copy_rows = (g_rows - 1) * FONT_H;
	u_int32_t y;

	for (y = 0; y < copy_rows; y++)
	{
		u_int8_t *dst = virtio_gpu_fb + (u_int64_t)y * virtio_gpu_pitch;
		u_int8_t *src = virtio_gpu_fb + (u_int64_t)(y + FONT_H) * virtio_gpu_pitch;
		memcpy(dst, src, virtio_gpu_width * 4);
	}
	for (y = copy_rows; y < g_rows * FONT_H; y++)
	{
		u_int32_t *row = (u_int32_t *)(virtio_gpu_fb + (u_int64_t)y * virtio_gpu_pitch);
		u_int32_t x;
		for (x = 0; x < virtio_gpu_width; x++)
			row[x] = BG;
	}
}

/**
 * kconsole putc: render one character, advancing the cursor and scrolling /
 * presenting as needed.  '\n' ends a line and flushes to the scanout.
 */
static void fbcon_putc(int ch)
{
	unsigned char c = (unsigned char)ch;

	if (!g_ready)
		return;

	switch (c)
	{
		case '\n':
			g_cx = 0;
			if (++g_cy >= g_rows)
			{
				fbcon_scroll();
				g_cy = g_rows - 1;
			}
			fbcon_present(); /* flush the completed line */
			return;
		case '\r':
			g_cx = 0;
			return;
		case '\b':
			if (g_cx > 0)
				g_cx--;
			return;
		case '\t':
			g_cx = (g_cx + 8) & ~7u;
			if (g_cx >= g_cols)
				g_cx = g_cols - 1;
			return;
		default:
			break;
	}

	fbcon_draw_glyph(g_cx, g_cy, c);
	if (++g_cx >= g_cols)
	{
		g_cx = 0;
		if (++g_cy >= g_rows)
		{
			fbcon_scroll();
			g_cy = g_rows - 1;
		}
	}
}

static struct kconsole g_fbcon = {fbcon_putc, "fbcon", KC_PRIMARY | KC_SUSPENDABLE, 0};

/**
 * Bring up the framebuffer console: if the GPU scanout is live, clear it and
 * register the primary sink so kprintf renders on screen.  Called from boot
 * after aarch64_virtio_gpu_init().  No-op (serial stays primary) if there is no
 * framebuffer.
 */
void aarch64_fbcon_init(void)
{
	if (virtio_gpu_fb == 0 || virtio_gpu_width == 0 || virtio_gpu_height == 0)
		return;

	g_cols = virtio_gpu_width / FONT_W;
	g_rows = virtio_gpu_height / FONT_H;
	g_cx = g_cy = 0;
	fbcon_fill(BG);
	fbcon_present();
	g_ready = 1;
	kconsole_register(&g_fbcon);
	kprintf("fbcon: %ux%u text console on the framebuffer (%ux%u px)\n",
	        g_cols,
	        g_rows,
	        virtio_gpu_width,
	        virtio_gpu_height);
}
