/* ------------------------------------------------------------------ */
/* Framebuffer methods                                                 */
/* ------------------------------------------------------------------ */

void
Framebuffer::put(uint8_t *row, int x, uint32_t color) const
{
	if (bpp == 32) {
		((uint32_t *)row)[x] = color;
	} else {
		uint8_t *p = row + (uint32_t)x * 3;
		p[0] =  color        & 0xFF;
		p[1] = (color >>  8) & 0xFF;
		p[2] = (color >> 16) & 0xFF;
	}
}

uint8_t *
Framebuffer::row_ptr(int y) const
{
	return (uint8_t *)base + (uint32_t)y * pitch;
}

int
Framebuffer::open()
{
	struct _fb_map info;
	if (_sys_mapfb(&info) != 0)
		return -1;
	width  = info.width;
	height = info.height;
	pitch  = info.pitch;
	bpp    = info.bpp;
	base   = info.base;
	return 0;
}

void
Framebuffer::pixel(int x, int y, uint32_t color)
{
	if (x < 0 || y < 0 ||
	    (uint32_t)x >= width || (uint32_t)y >= height)
		return;
	put(row_ptr(y), x, color);
}

void
Framebuffer::rect(int x, int y, int w, int h, uint32_t color)
{
	for (int r = y; r < y + h; r++) {
		if (r < 0 || (uint32_t)r >= height) continue;
		uint8_t *p = row_ptr(r);
		for (int c = x; c < x + w; c++) {
			if (c < 0 || (uint32_t)c >= width) continue;
			put(p, c, color);
		}
	}
}

void
Framebuffer::blit(int dx, int dy, int w, int h,
    const uint32_t *src, int src_stride)
{
	for (int r = 0; r < h; r++) {
		int dst_y = dy + r;
		if (dst_y < 0 || (uint32_t)dst_y >= height) continue;
		uint8_t *dst_row = row_ptr(dst_y);
		const uint32_t *src_row = src + r * src_stride;
		for (int c = 0; c < w; c++) {
			int dst_x = dx + c;
			if (dst_x < 0 || (uint32_t)dst_x >= width)
				continue;
			put(dst_row, dst_x, src_row[c]);
		}
	}
}

void
Framebuffer::ch(int x, int y, char c, uint32_t fg, uint32_t bg)
{
	uint8_t idx = (uint8_t)c;
	if (idx < 0x20 || idx > 0x7F) idx = 0x20;
	const uint8_t *glyph = font8x8[idx - 0x20];
	for (int row = 0; row < FB_FONT_H; row++) {
		uint8_t bits = glyph[row];
		for (int col = 0; col < FB_FONT_W; col++) {
			uint32_t color = (bits & (0x80 >> col)) ? fg : bg;
			pixel(x + col, y + row, color);
		}
	}
}

void
Framebuffer::text(int x, int y, const char *s, uint32_t fg, uint32_t bg)
{
	int cx = x;
	while (*s) {
		if (*s == '\n') { cx = x; y += FB_FONT_H; }
		else { ch(cx, y, *s, fg, bg); cx += FB_FONT_W; }
		s++;
	}
}

uint32_t
Framebuffer::read(int x, int y) const
{
	if (x < 0 || y < 0 ||
	    (uint32_t)x >= width || (uint32_t)y >= height)
		return 0;
	const uint8_t *p = row_ptr(y);
	if (bpp == 32)
		return ((const uint32_t *)p)[x];
	p += (uint32_t)x * 3;
	return (uint32_t)p[0] |
	       ((uint32_t)p[1] << 8) |
	       ((uint32_t)p[2] << 16);
}
